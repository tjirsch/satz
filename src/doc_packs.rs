type Catalogs = BTreeMap<(String, String), crate::compliance::Catalog>;

/// Every catalog the library's claims cite, loaded once and validated.
///
/// A framework with no catalog file, and a claim on a control the catalog does
/// not carry, are hard errors HERE — on the write path as much as under
/// `--check`, because the control's title is now rendered onto the page and a
/// blank title is exactly how a claim on a wrong id survives review. The CIS 4.0
/// alert claims were one id off the benchmark for weeks with no gate to say so.
fn catalogs(presets_dir: &Path, all: &[(PathBuf, File, String)]) -> Result<Catalogs, BoxErr> {
    let mut cats: Catalogs = BTreeMap::new();
    let mut bad = Vec::new();
    for (rel, file, _) in all {
        for c in &file.claims {
            let key = (c.framework.clone(), c.version.clone());
            if !cats.contains_key(&key) {
                let path = presets_dir.join("catalogs").join(format!("{}-{}.yaml", c.framework, c.version));
                let text = std::fs::read_to_string(&path).map_err(|e| {
                    format!("{}: claims {} {} but there is no catalog {} ({})", rel.display(), c.framework, c.version, path.display(), e)
                })?;
                let cat: crate::compliance::Catalog =
                    serde_yaml::from_str(&text).map_err(|e| format!("{}: {}", path.display(), e))?;
                cats.insert(key.clone(), cat);
            }
            if !cats[&key].controls.contains_key(&c.control) {
                bad.push(format!("{}: claim {} {} §{} — no such control in the catalog", rel.display(), c.framework, c.version, c.control));
            }
        }
    }
    if !bad.is_empty() {
        return Err(format!("{} claim(s) name a control their catalog does not carry:\n  {}", bad.len(), bad.join("\n  ")).into());
    }
    Ok(cats)
}

fn control<'a>(cats: &'a Catalogs, c: &satz::ClaimDecl) -> &'a crate::compliance::Control {
    cats.get(&(c.framework.clone(), c.version.clone()))
        .and_then(|cat| cat.controls.get(&c.control))
        .expect("catalogs() rejected every claim whose control its catalog does not carry")
}

/// One row of the changelog table at the foot of `presets/README.md`.
#[derive(Debug)]
struct Change {
    version: String,
    date: String,
    change: String,
}

type Changelog = BTreeMap<String, Vec<Change>>;

/// Split a Markdown table row on its unescaped pipes.
fn cells(row: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut escaped = false;
    for ch in row.trim().trim_start_matches('|').trim_end_matches('|').chars() {
        if escaped {
            cur.push(ch);
            escaped = false;
        } else if ch == '\\' {
            escaped = true;
            cur.push(ch);
        } else if ch == '|' {
            out.push(cur.trim().to_string());
            cur = String::new();
        } else {
            cur.push(ch);
        }
    }
    out.push(cur.trim().to_string());
    out
}

/// The pack history, read from the `## Changelog` table in `presets/README.md`.
///
/// Two gates ride along, and both used to live in a shell loop in the smoke
/// matrix: every row names a pack that exists, and every pack's current in-file
/// version has a row. Here they also run under `cargo test`, and the message can
/// name the line.
fn changelog(presets_dir: &Path, all: &[(PathBuf, File, String)]) -> Result<Changelog, BoxErr> {
    let path = presets_dir.join("README.md");
    let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: {}", path.display(), e))?;
    let lines: Vec<&str> = text.lines().collect();
    let at = |n: usize, msg: &str| -> BoxErr { format!("{}:{}: {}", path.display(), n + 1, msg).into() };

    let start = lines
        .iter()
        .position(|l| l.trim() == "## Changelog")
        .ok_or_else(|| -> BoxErr { format!("{}: no `## Changelog` section — the pack history lives at the foot of the preset library", path.display()).into() })?;
    let head = (start + 1..lines.len())
        .find(|&i| lines[i].trim_start().starts_with('|'))
        .ok_or_else(|| at(start, "the `## Changelog` section carries no table"))?;
    let want = ["pack", "version", "date", "change"];
    if cells(lines[head]) != want {
        return Err(at(head, "the changelog table's header must read `| pack | version | date | change |`"));
    }
    if !lines[head + 1].trim().chars().all(|c| matches!(c, '|' | '-' | ':' | ' ')) {
        return Err(at(head + 1, "the changelog table's header is not followed by a separator row"));
    }

    let known: BTreeSet<String> = all.iter().map(|(_, f, _)| f.estate.clone().unwrap_or_default()).collect();
    let mut hist: Changelog = BTreeMap::new();
    let mut seen: BTreeSet<(String, String)> = BTreeSet::new();
    for (n, row) in lines.iter().enumerate().skip(head + 2) {
        if !row.trim_start().starts_with('|') {
            break;
        }
        let c = cells(row);
        if c.len() != 4 {
            return Err(at(n, &format!("a changelog row has {} cells, not 4", c.len())));
        }
        let pack = c[0].trim_matches('`').to_string();
        if pack == c[0] {
            return Err(at(n, "the pack name in a changelog row must be in backticks"));
        }
        if !known.contains(&pack) {
            return Err(at(n, &format!("changelog row for `{}`, which is not a pack in the library", pack)));
        }
        if !seen.insert((pack.clone(), c[1].clone())) {
            return Err(at(n, &format!("`{}` {} has two changelog rows", pack, c[1])));
        }
        hist.entry(pack).or_default().push(Change { version: c[1].clone(), date: c[2].clone(), change: c[3].clone() });
    }

    let mut missing = Vec::new();
    for (rel, file, _) in all {
        let name = file.estate.clone().unwrap_or_default();
        let version = file.version.clone().unwrap_or_default();
        if !hist.get(&name).is_some_and(|rows| rows.iter().any(|r| r.version == version)) {
            missing.push(format!("presets/{}: `{}` {} has no changelog row", rel.display(), name, version));
        }
    }
    if !missing.is_empty() {
        return Err(format!(
            "{} pack version(s) with no row under `## Changelog` in presets/README.md — a bump and its reason ship together:\n  {}",
            missing.len(),
            missing.join("\n  ")
        )
        .into());
    }
    Ok(hist)
}

