//! `satz doc-packs`: one Markdown page per pristine pack, DERIVED from the
//! parser — header comment, the invocation that installs it, params with
//! defaults, resources, claims with their catalog titles, duties, and the
//! pack's own version history — plus an index of the library.
//! The hand-written part is a notes region the regeneration preserves.
//! `--check` fails when the committed pages are behind the packs: docs are
//! derived from the parser, never from intent.
//!
//! Every gate below runs on the WRITE path as much as under `--check`. A claim
//! on a control the catalog does not carry, a header with no summary, a pack
//! version with no changelog row: none of those may reach a page and be
//! discovered later. A generated page that is wrong is worse than none.

use satz_core::satz::{self, Entry, File, Key, StrPart, Value};
use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

type BoxErr = Box<dyn std::error::Error>;

const NOTES_START: &str = "<!-- notes:start — hand-written, kept across `satz doc-packs` -->";
const NOTES_END: &str = "<!-- notes:end -->";
const BANNER: &str = "<!-- generated by `satz doc-packs` from the pack file — edit the pack or the notes region, never the rest -->";

/// The index prints the summary in a table cell; a paragraph does not fit one.
const SUMMARY_MAX: usize = 160;

/// Every pristine pack under `presets_dir`: (relative path, parsed file, source text).
fn packs(presets_dir: &Path) -> Result<Vec<(PathBuf, File, String)>, BoxErr> {
    let mut out = Vec::new();
    let mut stack = vec![presets_dir.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let entries = std::fs::read_dir(&dir).map_err(|e| format!("{}: {}", dir.display(), e))?;
        for e in entries {
            let p = e?.path();
            if p.is_dir() {
                if p.file_name().is_some_and(|n| n == "docs") {
                    continue;
                }
                stack.push(p);
                continue;
            }
            let name = p.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if !name.ends_with(".satz") || name.contains(".local.") || name.ends_with(".diff.satz") {
                continue;
            }
            let src = std::fs::read_to_string(&p).map_err(|e| format!("{}: {}", p.display(), e))?;
            let file = satz::parse(&src).map_err(|e| format!("{}:{}: {}", p.display(), e.line, e.msg))?;
            if !file.is_pack {
                return Err(format!("{}: not a pack (no `pack` header) — an estate does not belong in the preset library", p.display()).into());
            }
            out.push((p.strip_prefix(presets_dir)?.to_path_buf(), file, src));
        }
    }
    out.sort_by(|a, b| a.0.cmp(&b.0));
    Ok(out)
}

fn key_text(k: &Key) -> String {
    match k {
        Key::Ident(s) => s.clone(),
        Key::Str(parts) => str_text(parts),
    }
}

fn str_text(parts: &[StrPart]) -> String {
    parts
        .iter()
        .map(|p| match p {
            StrPart::Lit(s) => s.clone(),
            StrPart::Param(r) => format!("{{{}}}", r),
        })
        .collect()
}

/// A value as the reader would write it.
fn value_text(v: &Value) -> String {
    match v {
        Value::Str(parts) => format!("\"{}\"", str_text(parts)),
        Value::Num(n) => n.clone(),
        Value::Bool(b) => b.to_string(),
        Value::Ref(r) => r.clone(),
        Value::List(items) => {
            let inner: Vec<String> = items.iter().map(value_text).collect();
            if inner.is_empty() {
                "[]".into()
            } else {
                format!("[ {} ]", inner.join(", "))
            }
        }
        Value::Obj(entries) => format!("{{ {} }}", entries.iter().map(entry_text).collect::<Vec<_>>().join(" ")),
    }
}

fn entry_text(e: &Entry) -> String {
    match e {
        Entry::Attr { key, value, .. } => format!("{} = {}", key_text(key), value_text(value)),
        Entry::Map { key, name, body, .. } => {
            let n = name.as_ref().map(|n| format!(" {}", key_text(n))).unwrap_or_default();
            format!("{}{} {{ {} }}", key_text(key), n, body.iter().map(entry_text).collect::<Vec<_>>().join(" "))
        }
        Entry::Use { path, as_key, when, .. } => {
            let mut s = format!("use \"{}\"", path);
            if let Some(a) = as_key {
                s.push_str(&format!(" as {}", a));
            }
            if let Some(w) = when {
                s.push_str(&format!(" when {}", w));
            }
            s
        }
    }
}

/// A binding as a pack file writes it: one line when it fits, one item per line
/// when it does not.
fn value_block(name: &str, v: &Value, indent: &str) -> String {
    let one = format!("{}{} = {}", indent, name, value_text(v));
    if one.chars().count() <= 78 {
        return one;
    }
    if let Value::List(items) = v {
        let mut s = format!("{}{} = [\n", indent, name);
        for i in items {
            s.push_str(&format!("{}  {},\n", indent, value_text(i)));
        }
        s.push_str(&format!("{}]", indent));
        return s;
    }
    one
}

// ---------------------------------------------------------------------------
// The header comment: what the pack is for, and how it is used
// ---------------------------------------------------------------------------

/// The comment block above the `pack` header, split. The author's statement of
/// purpose, and the ONE canonical line saying how the pack is included — which
/// the page renders structurally, so it is lifted out of the prose rather than
/// printed twice. The converter's provenance line is neither.
#[derive(Default)]
struct Header {
    purpose: Vec<String>,
    invocation: Option<String>,
}

/// A header line is this pack's canonical invocation when it is a bare `use` of
/// the pack's OWN path, or a resource map wrapping one. A line naming ANOTHER
/// pack's path is prose about that pack and stays in the purpose.
fn is_invocation(line: &str, rel: &Path) -> bool {
    if !line.contains(&format!("\"presets/{}\"", rel.display())) {
        return false;
    }
    line.starts_with("use ") || (line.ends_with('}') && line.contains("{ use "))
}

fn header(src: &str, rel: &Path) -> Result<Header, BoxErr> {
    let mut h = Header::default();
    for line in src.lines() {
        let t = line.trim();
        if t.starts_with("pack ") {
            break;
        }
        let Some(c) = t.strip_prefix("//").or_else(|| t.strip_prefix('#')) else {
            if t.is_empty() {
                continue;
            }
            break;
        };
        let c = c.trim();
        if c.starts_with("Converted by") || c.starts_with("Converted from") {
            continue;
        }
        if is_invocation(c, rel) {
            if h.invocation.is_some() {
                return Err(format!(
                    "presets/{}: the header spells this pack's own `use` twice — the page renders it once, so one line has to be the canonical one",
                    rel.display()
                )
                .into());
            }
            h.invocation = Some(c.to_string());
            continue;
        }
        h.purpose.push(c.to_string());
    }
    // a lifted line leaves a blank run behind
    let mut trimmed: Vec<String> = Vec::new();
    for l in h.purpose {
        if l.is_empty() && trimmed.last().is_some_and(|p: &String| p.is_empty()) {
            continue;
        }
        trimmed.push(l);
    }
    while trimmed.last().is_some_and(|l| l.is_empty()) {
        trimmed.pop();
    }
    while trimmed.first().is_some_and(|l| l.is_empty()) {
        trimmed.remove(0);
    }
    h.purpose = trimmed;
    Ok(h)
}

/// The one line the index prints for this pack: the first sentence of the
/// header. Gated, because a heuristic over prose nobody is required to write is
/// how the index became a table of file names in the first place.
fn summary(h: &Header, rel: &Path) -> Result<String, BoxErr> {
    let at = |msg: &str| -> BoxErr { format!("presets/{}: {}", rel.display(), msg).into() };
    let first: Vec<&String> = h.purpose.iter().take_while(|l| !l.is_empty()).collect();
    if first.is_empty() {
        return Err(at("no header comment — the lines above `pack` are what the index prints for it; open with one sentence saying what it does"));
    }
    let para = first.iter().map(|l| l.as_str()).collect::<Vec<_>>().join(" ");
    if para.starts_with("http://") || para.starts_with("https://") {
        return Err(at("the summary is a bare URL — say what the pack does, and put the reference on a later line"));
    }
    if para.starts_with("Include") || para.starts_with("use \"") || para.contains("!include") {
        return Err(at("an include instruction where the summary should be — say what the pack DOES; how it is used goes on its own `use` line"));
    }
    // first sentence: a period followed by space and a capital, or the whole text
    let bytes: Vec<char> = para.chars().collect();
    let mut end = bytes.len();
    for i in 0..bytes.len().saturating_sub(2) {
        if bytes[i] == '.' && bytes[i + 1] == ' ' && bytes[i + 2].is_uppercase() {
            end = i + 1;
            break;
        }
    }
    let s: String = bytes[..end].iter().collect();
    if s.chars().count() > SUMMARY_MAX {
        return Err(at(&format!(
            "the first sentence is {} characters — the index prints it in a table cell; open with a short one and keep the detail below",
            s.chars().count()
        )));
    }
    Ok(s)
}

// ---------------------------------------------------------------------------
// What a pack contributes
// ---------------------------------------------------------------------------

/// One resource a pack contributes. `typ` is `None` for a bare-list pack, whose
/// resource map the estate supplies. `off` marks a policy declared with
/// `spec { reset = true }` — a superseded legacy twin, which proves nothing by
/// design and must not read as an unwitnessed resource.
struct Res {
    typ: Option<String>,
    label: String,
    off: bool,
}

/// What a pack contributes: typed resource maps (type → labels), bare labels
/// (keyed by the estate's map), attribute-shaped entries, and `use` lines.
#[derive(Default)]
struct Shape {
    typed: BTreeMap<String, Vec<String>>,
    bare: Vec<String>,
    uses: Vec<String>,
    /// the same resources, addressable — grant maps and nested `use`s excluded,
    /// because a grant's emitted address comes from its member and role, not
    /// from the key, and joining it to a witness would report every grant as
    /// unclaimed
    resources: Vec<Res>,
}

fn declared_off(body: &[Entry]) -> bool {
    body.iter().any(|e| match e {
        Entry::Map { key, body, .. } => {
            key_text(key) == "spec"
                && body.iter().any(|b| matches!(b, Entry::Attr { key, value: Value::Bool(true), .. } if key_text(key) == "reset"))
        }
        _ => false,
    })
}

fn shape(items: &[Entry]) -> Shape {
    let mut s = Shape::default();
    for e in items {
        match e {
            Entry::Map { key, name: None, body, .. } => {
                let k = key_text(key);
                if k.starts_with("google_") {
                    let labels: Vec<String> = body
                        .iter()
                        .map(|b| match b {
                            Entry::Map { key, body, .. } => {
                                s.resources.push(Res { typ: Some(k.clone()), label: key_text(key), off: declared_off(body) });
                                key_text(key)
                            }
                            Entry::Attr { key, .. } => format!("{} (grant map)", key_text(key)),
                            Entry::Use { .. } => entry_text(b),
                        })
                        .collect();
                    s.typed.entry(k).or_default().extend(labels);
                } else {
                    s.resources.push(Res { typ: None, label: k.clone(), off: declared_off(body) });
                    s.bare.push(k);
                }
            }
            Entry::Map { key, name: Some(n), .. } => s.bare.push(format!("{} {}", key_text(key), key_text(n))),
            Entry::Attr { key, .. } => s.bare.push(format!("{} (attribute)", key_text(key))),
            Entry::Use { .. } => s.uses.push(entry_text(e)),
        }
    }
    s
}

/// The resource type a bare-list pack's own claims say its labels land in.
/// One type resolves; none or several is the author's to state.
fn bare_type(file: &File) -> Option<String> {
    let types: BTreeSet<&str> = file.claims.iter().flat_map(|c| &c.resources).filter_map(|r| r.split('.').next()).collect();
    match types.len() {
        1 => types.into_iter().next().map(str::to_string),
        _ => None,
    }
}

/// The line that installs this pack, from the header when it states one and
/// from the pack's own shape when it does not. Never a guess: a pack whose shape
/// does not decide it has to say so itself.
fn invocation(rel: &Path, file: &File, sh: &Shape, h: &Header) -> Result<String, BoxErr> {
    if let Some(inv) = &h.invocation {
        return Ok(inv.clone());
    }
    let path = format!("\"presets/{}\"", rel.display());
    if !sh.typed.is_empty() && !sh.bare.is_empty() {
        return Err(format!(
            "presets/{}: the pack mixes typed resource maps with bare labels, so neither `use` form fits it — split it, or state the canonical line in the header",
            rel.display()
        )
        .into());
    }
    if !sh.typed.is_empty() || sh.bare.is_empty() {
        return Ok(format!("use {}", path));
    }
    match bare_type(file) {
        Some(t) => Ok(format!("{} {{ use {} }}", t, path)),
        None => Err(format!(
            "presets/{}: nothing says how this pack is used. It is a bare list of labels, so the estate keys it by a \
             resource map and the pack has to name which one — add the canonical line to the header comment, e.g.\n    \
             google_organization_iam_member {{ use {} }}",
            rel.display(),
            path
        )
        .into()),
    }
}

