/// The directory a pack lives in — the library's own grouping.
fn family(rel: &Path) -> String {
    rel.parent().map(|p| p.to_string_lossy().to_string()).unwrap_or_default()
}

/// Control ids sort as numbers, not as text: 1.10 comes after 1.9.
fn control_order(id: &str) -> Vec<u32> {
    id.split('.').map(|p| p.parse().unwrap_or(u32::MAX)).collect()
}

struct Row {
    rel: PathBuf,
    name: String,
    version: String,
    summary: String,
    resources: usize,
    frameworks: Vec<String>,
    claims: usize,
    /// (framework, version, control) — what the coverage table counts
    claimed: Vec<(String, String, String)>,
}

fn index(rows: &[Row], cats: &Catalogs) -> String {
    let mut md = String::from(BANNER);
    md.push_str("\n# Preset packs\n\n");
    md.push_str(
        "One page per pristine pack, derived from the pack file by `satz doc-packs`. The library's \
         conventions and its per-family prose are [`presets/README.md`](../README.md); its version \
         history is [the changelog](../README.md#changelog) at the foot of that page, repeated per \
         pack under **History** on each page here.\n\n",
    );
    let resources: usize = rows.iter().map(|r| r.resources).sum();
    let claims: usize = rows.iter().map(|r| r.claims).sum();
    let frameworks: Vec<String> = cats.keys().map(|(f, v)| format!("{} {}", f, v)).collect();
    md.push_str(&format!(
        "**{} packs · {} resources · {} claims{}.**\n\n",
        rows.len(),
        resources,
        claims,
        if frameworks.is_empty() { String::new() } else { format!(" over {}", frameworks.join(" and ")) }
    ));

    let mut families: BTreeMap<String, Vec<&Row>> = BTreeMap::new();
    for r in rows {
        families.entry(family(&r.rel)).or_default().push(r);
    }
    // the root family first, then the directories alphabetically
    let mut order: Vec<&String> = families.keys().collect();
    order.sort_by_key(|f| (!f.is_empty(), (*f).clone()));
    for fam in order {
        md.push_str(&match fam.is_empty() {
            true => "## Root — `presets/*.satz`\n\n".to_string(),
            false => format!("## `{}/`\n\n", fam),
        });
        md.push_str("| pack | version | what it does | resources | claims |\n|---|---|---|---|---|\n");
        for r in &families[fam] {
            let stem = r.rel.file_stem().and_then(|s| s.to_str()).unwrap_or("");
            md.push_str(&format!(
                "| [`{}`]({}.md) | {} | {} | {} | {} |\n",
                r.name,
                stem,
                r.version,
                r.summary.replace('|', "\\|"),
                r.resources,
                match r.claims {
                    0 => "—".to_string(),
                    n => format!("{} — {}", n, r.frameworks.join(", ")),
                }
            ));
        }
        md.push('\n');
    }

    if !cats.is_empty() {
        md.push_str("## Framework coverage\n\n");
        md.push_str(
            "What some pack in this library CLAIMS — never a verdict on an estate. A claim is proof \
             only once its witnesses are emitted; `satz require <framework> <estate>` judges an \
             estate.\n\n",
        );
        md.push_str("| framework | controls in the catalog | claimed by a pack | claimed by none |\n|---|---|---|---|\n");
        for ((f, v), cat) in cats {
            let claimed: BTreeSet<&str> = rows
                .iter()
                .flat_map(|r| &r.claimed)
                .filter(|(cf, cv, _)| cf == f && cv == v)
                .map(|(_, _, id)| id.as_str())
                .collect();
            let mut gaps: Vec<&String> = cat.controls.keys().filter(|k| !claimed.contains(k.as_str())).collect();
            gaps.sort_by_key(|id| control_order(id));
            md.push_str(&format!(
                "| {} {} | {} | {} | {} |\n",
                f,
                v,
                cat.controls.len(),
                claimed.len(),
                if gaps.is_empty() { "—".to_string() } else { gaps.iter().map(|g| g.as_str()).collect::<Vec<_>>().join(", ") }
            ));
        }
        md.push('\n');
    }
    md
}

/// Generate (or, with `check`, verify) `presets/docs/`.
pub(crate) fn run(presets_dir: &Path, out_dir: &Path, check: bool) -> Result<(), BoxErr> {
    let all = packs(presets_dir)?;
    if all.is_empty() {
        return Err(format!("{}: no packs found", presets_dir.display()).into());
    }
    let cats = catalogs(presets_dir, &all)?;
    let hist = changelog(presets_dir, &all)?;
    let lib = library(&all);

    // Header problems are collected and reported together: fixing them is one
    // pass over the library, not nine rounds of one error each.
    let mut headers = Vec::new();
    let mut errs = Vec::new();
    for (rel, _, src) in &all {
        match header(src, rel) {
            Ok(h) => headers.push(h),
            Err(e) => {
                errs.push(e.to_string());
                headers.push(Header::default());
            }
        }
    }
    let mut summaries = Vec::new();
    for ((rel, _, _), h) in all.iter().zip(&headers) {
        match summary(h, rel) {
            Ok(s) => summaries.push(s),
            Err(e) => {
                errs.push(e.to_string());
                summaries.push(String::new());
            }
        }
    }
    if !errs.is_empty() {
        return Err(format!("{} pack header(s) need work:\n  {}", errs.len(), errs.join("\n  ")).into());
    }

    let mut stale = Vec::new();
    let mut written = 0;
    let mut pages: Vec<(PathBuf, String)> = Vec::new();
    let mut rows: Vec<Row> = Vec::new();
    let empty: Vec<Change> = Vec::new();
    for (((rel, file, _), h), sum) in all.iter().zip(&headers).zip(&summaries) {
        let stem = rel.file_stem().and_then(|s| s.to_str()).unwrap_or("pack");
        let out = out_dir.join(format!("{}.md", stem));
        let existing = std::fs::read_to_string(&out).ok();
        let name = file.estate.clone().unwrap_or_default();
        let history = hist.get(&name).unwrap_or(&empty);
        pages.push((out, render(rel, file, h, existing.as_deref(), &cats, history, &lib)?));
        let sh = shape(&file.items);
        let mut frameworks: Vec<String> = file.claims.iter().map(|c| format!("{} {}", c.framework, c.version)).collect();
        frameworks.sort();
        frameworks.dedup();
        rows.push(Row {
            rel: rel.clone(),
            name,
            version: file.version.clone().unwrap_or_else(|| "unversioned".into()),
            summary: sum.clone(),
            resources: sh.typed.values().map(|l| l.len()).sum::<usize>() + sh.bare.len(),
            frameworks,
            claims: file.claims.len(),
            claimed: file
                .claims
                .iter()
                .map(|c| (c.framework.clone(), c.version.clone(), c.control.clone()))
                .collect(),
        });
    }
    pages.push((out_dir.join("README.md"), index(&rows, &cats)));
    for (out, text) in pages {
        let current = std::fs::read_to_string(&out).ok();
        if current.as_deref() == Some(text.as_str()) {
            continue;
        }
        if check {
            stale.push(out);
        } else {
            std::fs::create_dir_all(out_dir)?;
            std::fs::write(&out, &text).map_err(|e| format!("{}: {}", out.display(), e))?;
            written += 1;
        }
    }
    if check {
        if !stale.is_empty() {
            return Err(format!(
                "doc-packs: {} page(s) behind the packs — run `satz doc-packs` and commit: {}",
                stale.len(),
                stale.iter().map(|p| p.display().to_string()).collect::<Vec<_>>().join(", ")
            )
            .into());
        }
        println!("doc-packs: {} page(s) current", all.len() + 1);
    } else {
        println!("doc-packs: {} pack(s), {} page(s) written to {}", all.len(), written, out_dir.display());
    }
    Ok(())
}

