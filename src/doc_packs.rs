/// `google_x` + `some-label` → the address the emitter writes, which is the
/// address a claim witnesses.
fn address(typ: &str, label: &str) -> String {
    format!("{}.{}", typ, label.replace('-', "_"))
}

fn use_it(rel: &Path, file: &File, sh: &Shape, h: &Header, lib: &Library) -> Result<String, BoxErr> {
    let inv = invocation(rel, file, sh, h)?;
    let gate = inv.split(" when ").nth(1).map(|s| s.trim().to_string());

    let mut md = String::from("## Use it\n\n```\n");
    if gate.is_some() || !file.params.is_empty() {
        md.push_str("params {\n");
        if let Some(g) = &gate {
            md.push_str(&format!("  {} = true\n", g));
            if !file.params.is_empty() {
                md.push('\n');
            }
        }
        if !file.params.is_empty() {
            md.push_str("  // the pack's own defaults — copy only the lines you change\n");
            for (n, v, _) in &file.params {
                md.push_str(&value_block(n, v, "  "));
                md.push('\n');
            }
        }
        md.push_str("}\n\n");
    }
    md.push_str(&inv);
    md.push_str("\n```\n\n");

    if let Some(g) = &gate {
        let by = lib.get(g).map(|packs| {
            packs.iter().map(|p| format!("`{}`", p)).collect::<Vec<_>>().join(", ")
        });
        md.push_str(&format!(
            "`{}` is the gate: while it is falsy the pack contributes nothing — no resources, no params, no claims. {}\n\n",
            g,
            match by {
                Some(p) => format!("It is declared by {}, and the estate's own binding wins.", p),
                None => "The param must be DECLARED somewhere — a `when` on a param nobody declares is an error, not `false`.".into(),
            }
        ));
    }
    if file.params.is_empty() && gate.is_none() {
        md.push_str("The pack declares no params: everything it sets is fixed in the file. A different value is a param lifted into the pack, or a `.local` fork.\n\n");
    }

    let outside = needs(file);
    if !outside.is_empty() {
        md.push_str("**Needs from outside the pack:**\n\n");
        for n in &outside {
            match lib.get(n) {
                Some(packs) => md.push_str(&format!(
                    "- `{}` — declared by {}; use one of them alongside, or declare it in the estate.\n",
                    n,
                    packs.iter().map(|p| format!("`{}`", p)).collect::<Vec<_>>().join(", ")
                )),
                None => md.push_str(&format!("- `{}` — no pack in the library declares it, so the estate must.\n", n)),
            }
        }
        md.push('\n');
    }
    Ok(md)
}

/// Which contributed resources no claim on this page witnesses — and, of those,
/// which are superseded legacy twins declared off, which prove nothing by design.
fn claim_coverage(sh: &Shape, file: &File) -> String {
    let witnesses: BTreeSet<&str> = file.claims.iter().flat_map(|c| &c.resources).map(String::as_str).collect();
    let bare = bare_type(file);
    let mut unclaimed = Vec::new();
    for r in &sh.resources {
        let Some(typ) = r.typ.as_deref().or(bare.as_deref()) else { continue };
        let addr = address(typ, &r.label);
        if witnesses.contains(addr.as_str()) {
            continue;
        }
        unclaimed.push(if r.off {
            format!("- `{}` — declared OFF (`spec {{ reset = true }}`): a superseded legacy twin, which proves nothing by design.\n", addr)
        } else {
            format!("- `{}` — contributed, but no claim names it.\n", addr)
        });
    }
    if unclaimed.is_empty() {
        return "Every resource this pack contributes is a witness of a claim above.\n\n".into();
    }
    format!("Not every resource this pack contributes is a witness:\n\n{}\n", unclaimed.concat())
}

fn render(
    rel: &Path,
    file: &File,
    h: &Header,
    existing: Option<&str>,
    cats: &Catalogs,
    history: &[Change],
    lib: &Library,
) -> Result<String, BoxErr> {
    let name = file.estate.clone().unwrap_or_default();
    let version = file.version.clone().unwrap_or_else(|| "unversioned".into());
    let sh = shape(&file.items);
    let mut md = String::new();
    md.push_str(BANNER);
    md.push('\n');
    md.push_str(&format!("# `{}` — version {}{}\n\n", name, version, if file.content_mode { " · content pack" } else { "" }));
    md.push_str(&format!("Source: `presets/{}`", rel.display()));
    if file.content_mode {
        md.push_str(" — a **content** pack: forking it into `<name>.local.satz` is the expected workflow (per-customer content).");
    }
    md.push_str("\n\n");
    if !h.purpose.is_empty() {
        md.push_str("## Purpose\n\n");
        md.push_str(&h.purpose.join("\n"));
        md.push_str("\n\n");
    }
    md.push_str(&use_it(rel, file, &sh, h, lib)?);
    md.push_str("## Params\n\n");
    if file.params.is_empty() {
        md.push_str("_None — the pack takes everything from the estate's params._\n\n");
    } else {
        md.push_str("| param | default |\n|---|---|\n");
        for (n, v, _) in &file.params {
            md.push_str(&format!("| `{}` | `{}` |\n", n, value_text(v).replace('|', "\\|")));
        }
        md.push('\n');
    }
    // A SECTION, not a column on the params table: a column rewrites all 25
    // generated pages, a section touches only packs that declare a question.
    if !file.questions.is_empty() {
        md.push_str("## Questions\n\n");
        md.push_str("What to ask before this pack is configured, and what changing the answer costs.\n\n");
        md.push_str("| asks about | prompt | reversal | blast | recommends |\n|---|---|---|---|---|\n");
        for q in &file.questions {
            md.push_str(&format!(
                "| `{}`{} | {} | {} | {} | {} |\n",
                q.subject,
                if q.oneof { " *(choice)*" } else { "" },
                q.prompt.replace('|', "\\|"),
                q.reversal.as_str(),
                q.blast.as_str(),
                q.recommend.as_ref().map(|v| format!("`{}`", value_text(v).replace('|', "\\|"))).unwrap_or_else(|| "—".into()),
            ));
        }
        md.push('\n');
        for q in &file.questions {
            if q.options.is_empty() && q.why.is_none() {
                continue;
            }
            md.push_str(&format!("**{}** — {}\n\n", q.subject, q.why.as_deref().unwrap_or("")));
            for o in &q.options {
                md.push_str(&format!(
                    "- `{}` — {}{}\n",
                    o.param,
                    o.label,
                    o.why.as_ref().map(|w| format!(" ({})", w)).unwrap_or_default()
                ));
            }
            md.push('\n');
        }
    }

    let off: BTreeSet<&str> = sh.resources.iter().filter(|r| r.off).map(|r| r.label.as_str()).collect();
    let mark = |l: &String| if off.contains(l.as_str()) { format!("`{}` *(off)*", l) } else { format!("`{}`", l) };
    md.push_str("## Contributes\n\n");
    if !sh.uses.is_empty() {
        for u in &sh.uses {
            md.push_str(&format!("- `{}`\n", u));
        }
        md.push('\n');
    }
    if !sh.typed.is_empty() {
        md.push_str("| resource type | labels |\n|---|---|\n");
        for (t, labels) in &sh.typed {
            md.push_str(&format!("| `{}` | {} |\n", t, labels.iter().map(mark).collect::<Vec<_>>().join(", ")));
        }
        md.push('\n');
    }
    if !sh.bare.is_empty() {
        md.push_str(&format!(
            "A bare list — keyed by the estate's resource map (`google_x {{ use \"presets/{}\" }}` or `use … as google_x`): {}.\n\n",
            rel.display(),
            sh.bare.iter().map(mark).collect::<Vec<_>>().join(", ")
        ));
    }
    if sh.typed.is_empty() && sh.bare.is_empty() && sh.uses.is_empty() {
        // A pack whose whole content is an action declares no resources on
        // purpose — saying "params and claims only" there would describe it as
        // missing something it was never meant to have.
        if file.actions.is_empty() {
            md.push_str("_No resources — params and claims only._\n\n");
        } else {
            md.push_str("_No resources: this pack's content is the action below — a step with no provider binding._\n\n");
        }
    }
    if !file.hcl_blocks.is_empty() {
        md.push_str(&format!("**Raw HCL:** {} `hcl` block(s)", file.hcl_blocks.len()));
        let trusted: Vec<&str> = file.hcl_blocks.iter().filter_map(|h| h.trust.as_deref()).collect();
        if !trusted.is_empty() {
            md.push_str(&format!(" — trusted: {}", trusted.iter().map(|t| format!("\"{}\"", t)).collect::<Vec<_>>().join(", ")));
        }
        md.push_str(". Opaque to the compliance plane.\n\n");
    }
    if !file.suppressions.is_empty() {
        md.push_str(&format!("**Suppressions:** {}.\n\n", file.suppressions.len()));
    }
    // A pack that ships an executable step must say so on its own page. Whoever
    // installs it with `get-presets` should not have to open the .satz to find out
    // that `run-actions` would run something.
    if !file.actions.is_empty() {
        md.push_str(&format!(
            "**Actions:** {} — `satz run-actions` executes {}. Not covered by any claim.\n\n",
            file.actions.len(),
            file.actions
                .iter()
                .map(|a| format!("`{}` (`{}`)", a.name, a.run))
                .collect::<Vec<_>>()
                .join(", ")
        ));
        for a in &file.actions {
            md.push_str(&format!("- `{}` — {} (phase `{}`)\n", a.name, a.reason, a.phase));
        }
        md.push('\n');
    }
    md.push_str("## Claims\n\n");
    if file.claims.is_empty() {
        md.push_str("_None — this pack proves no control by itself._\n\n");
    } else {
        md.push_str("| framework | control | title | kind | witnesses | interpretation |\n|---|---|---|---|---|---|\n");
        for c in &file.claims {
            let kind = match c.coverage.as_str() {
                "deviates" => format!("**deviates** — {}", c.reason.clone().unwrap_or_default()),
                k => k.to_string(),
            };
            md.push_str(&format!(
                "| {} {} | {} | {} | {} | {} | {} |\n",
                c.framework,
                c.version,
                c.control,
                control(cats, c).title.replace('|', "\\|"),
                kind,
                c.resources.iter().map(|r| format!("`{}`", r)).collect::<Vec<_>>().join("<br>"),
                c.interpretation.clone().unwrap_or_default().replace('|', "\\|")
            ));
        }
        md.push('\n');
        // 4.0 and 5.0 carry identical titles and paraphrases for most controls —
        // fold them the way the duties below are folded, or the same sentence
        // appears twice under every claim pair.
        let mut asks: BTreeMap<(String, String), Vec<String>> = BTreeMap::new();
        for c in &file.claims {
            let ctl = control(cats, c);
            let tag = format!("{} {} §{}", c.framework, c.version, c.control);
            let e = asks.entry((ctl.title.clone(), ctl.paraphrase.clone())).or_default();
            if !e.contains(&tag) {
                e.push(tag);
            }
        }
        md.push_str("**What the controls ask** (this project's paraphrase from the catalog — never the framework's own text):\n\n");
        for ((title, paraphrase), tags) in &asks {
            md.push_str(&format!("- **{}** ({})", title, tags.join(", ")));
            if !paraphrase.is_empty() {
                md.push_str(&format!(" — {}", paraphrase));
            }
            md.push('\n');
        }
        md.push('\n');
        // one duty may serve the same control in two framework versions —
        // list it once, with every control it holds partial
        let mut duties: BTreeMap<(String, String), Vec<String>> = BTreeMap::new();
        for c in &file.claims {
            for (id, text) in &c.duties {
                let controls = duties.entry((id.clone(), text.clone())).or_default();
                let tag = format!("{} {} §{}", c.framework, c.version, c.control);
                if !controls.contains(&tag) {
                    controls.push(tag);
                }
            }
        }
        if !duties.is_empty() {
            md.push_str("**Manual duties** (a control stays *partial* until each is attested):\n\n");
            for ((id, text), controls) in duties {
                md.push_str(&format!("- `{}` ({}) — {}\n", id, controls.join(", "), text.replace('\n', " ")));
            }
            md.push('\n');
        }
        md.push_str(&claim_coverage(&sh, file));
    }
    md.push_str("## History\n\n");
    md.push_str("| version | date | change |\n|---|---|---|\n");
    for c in history {
        md.push_str(&format!("| {} | {} | {} |\n", c.version, c.date, c.change));
    }
    md.push_str("\nThe whole library's history: [the changelog](../README.md#changelog) in `presets/README.md`.\n\n");
    md.push_str("## Notes\n\n");
    md.push_str(&notes_region(existing));
    md.push('\n');
    Ok(md)
}

fn notes_region(existing: Option<&str>) -> String {
    if let Some(text) = existing {
        if let (Some(a), Some(b)) = (text.find(NOTES_START), text.find(NOTES_END)) {
            if a < b {
                return text[a..b + NOTES_END.len()].to_string();
            }
        }
    }
    format!("{}\n\n_No notes yet._\n\n{}", NOTES_START, NOTES_END)
}

